import com.bedtime.dreamtales.data.local.entity.Story

data class CuratedPackStory(
    val title: String,
    val targetAge: String,
    val iconEmoji: String,
    val summary: String,
    val content: String,
    val durationSeconds: Int = 150
) {
    fun toStory(packTitle: String, createdAt: Long = System.currentTimeMillis()): Story = Story(
        title = title,
        targetAge = targetAge,
        content = content,
        durationSeconds = durationSeconds,
        isAiGenerated = false,
        dateLabel = "故事处方 · $packTitle",
        iconEmoji = iconEmoji,
        playCount = 0,
        isFavorite = false,
        createdAt = createdAt
    )
}

